def patch_titles():
    n = 0
    # 1) 그래픽 제목
    lines = io.open(TITLES, encoding='utf-8').read().split('\n')
    for idx, off, new, why in TITLE:
        for i, l in enumerate(lines):
            if l.startswith(idx + '|'):
                p = l.split('|')
                old = ' '.join(x.strip() for x in p[2:]).strip()
                if old != new:
                    L('#57·#59·#61·#67', '그래픽 %s' % idx, old, new, why)
                    lines[i] = '%s|%s|%s' % (p[0], p[1], new)
                    n += 1
                break
    if WRITE:
        io.open(TITLES, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
    # 2) 시스템 텍스트
    d = json.load(open(TRANS, encoding='utf-8'))
    for idx, off, new, why in TITLE:
        snew = to_sys(new)
        for e in d['entries']:
            if e['off'] == off:
                if e['ko'] != snew:
                    L('#57·#59·#61·#67', '시스템 %s' % off[-6:], e['ko'], '%s (%d칸)' % (snew, len(snew)), why)
                    if WRITE:
                        e['ko'] = snew
                    n += 1
                break
        else:
            L('#57', off, '(주소 없음)', snew, why)
    if WRITE:
        json.dump(d, open(TRANS, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    return n


def patch_xlsx():
    from openpyxl import load_workbook
    wb = load_workbook(XLSX)
    ws = wb[wb.sheetnames[0]]
    n = 0
    for row, old, new, iss, why in SC:
        if old == new:
            continue
        c = ws.cell(row=row, column=10)
        v = str(c.value or '')
        if old in v:
            nv = v.replace(old, new)
            L(iss, 'R%d' % row, v, nv, why)
            if WRITE:
                c.value = nv
            n += 1
        else:
            L(iss, 'R%d' % row, '(못 찾음) ' + old, repr(v)[:90], why)
    for row, new, iss, why in SC_WHOLE:
        c = ws.cell(row=row, column=10)
        v = str(c.value or '')
        if v != new:
            L(iss, 'R%d' % row, v, new, why)
            if WRITE:
                c.value = new
            n += 1
    if WRITE:
        wb.save(XLSX)
    return n


def patch_battle():
    d = json.load(open(BATTLE, encoding='utf-8'))
    ent = d['entries']
    n = 0
    for old, new, iss, why in BT_SUB:
        c = 0
        for i, e in enumerate(ent):
            ko = e.get('ko') or ''
            if old in ko:
                nv = ko.replace(old, new)
                if c < 2:
                    L(iss, 'i%d blk%s' % (i, e['blk']), ko, nv, why)
                if WRITE:
                    e['ko'] = nv
                c += 1
                n += 1
        L(iss, '합계', '%s → %s' % (old, new), '%d건' % c, '')
    for old, new, blk, iss, why in BT_FIX:
        c = 0
        for i, e in enumerate(ent):
            if blk is not None and e['blk'] != blk:
                continue
            ko = e.get('ko') or ''
            if old in ko:
                nv = ko.replace(old, new)
                L(iss, 'i%d blk%s' % (i, e['blk']), ko, nv, why)
                if WRITE:
                    e['ko'] = nv
                c += 1
                n += 1
        if not c:
            L(iss, '(못 찾음)', old, new, why)
    if WRITE:
        json.dump(d, open(BATTLE, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    return n


