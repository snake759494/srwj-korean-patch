# ── #3-3 서브파일럿 판본 경어가 뒤바뀐 쌍 (두 행의 본문을 맞바꾼다) ──
SWAP_PAIRS = [
    (21943, 21944, 'blk97 — 원문은 0x28 이 ①さん, 0x29 가 まって① 인데 번역이 반대'),
    (25709, 25716, 'blk111 — 원문은 뒤쪽이 ①さん 인데 번역의 경어가 앞쪽에 붙음'),
    (26396, 26397, 'blk113(44화) — 원문은 0x2A 가 ①さん 인데 번역의 씨가 0x29 에'),
    (26401, 26402, 'blk113(44화) — 같은 장면 반복분'),
]


def main():
    from openpyxl import load_workbook
    wb = load_workbook(XLSX)
    ws = wb[wb.sheetnames[0]]
    n = 0

    for row, old, new, why in NAME_FIX:
        c = ws.cell(row=row, column=10)
        v = str(c.value or '')
        if old in v:
            nv = v.replace(old, new)
            log.append(('#4 이름', 'R%d' % row, v, nv, why))
            if WRITE:
                c.value = nv
            n += 1
        else:
            log.append(('#4 이름', 'R%d' % row, '(못 찾음) %s' % old, '-', why))

    for row, new, jp in RELAY_FIX:
        c = ws.cell(row=row, column=10)
        v = str(c.value or '')
        if v != new:
            log.append(('#2 통역말투', 'R%d' % row, v, new, '원문 ' + jp))
            if WRITE:
                c.value = new
            n += 1

    for a, b, why in SWAP_PAIRS:
        ca, cb = ws.cell(row=a, column=10), ws.cell(row=b, column=10)
        va, vb = str(ca.value or ''), str(cb.value or '')
        log.append(('#3 경어맞바꿈', 'R%d ↔ R%d' % (a, b), va + '  ||  ' + vb, vb + '  ||  ' + va, why))
        if WRITE:
            ca.value, cb.value = vb, va
        n += 2

    if WRITE:
        wb.save(XLSX)
    return n


if __name__ == '__main__':
    sys.stdout.reconfigure(encoding='utf-8')
    print('모드:', '반영(--write)' if WRITE else '미리보기')
    n = main()
    for kind, where, before, after, why in log:
        print('\n[%s] %s — %s' % (kind, where, why))
        print('   - %s' % before.replace('\n', ' ⏎ ')[:160])
        print('   + %s' % after.replace('\n', ' ⏎ ')[:160])
    print('\n총 %d개 턴' % n)
